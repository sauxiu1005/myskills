def text_width(s, scale=1, gap=1):
    w = 0
    for ch in s:
        w += (len(G[ch][0]) + gap) * scale
    return w - gap * scale


def draw_text(cv, x, y, s, color, scale=1, gap=1, shadow=None, align="left"):
    """在逻辑网格上画像素数字串；shadow 为 1 格右下硬投影色。返回宽度。"""
    w = text_width(s, scale, gap)
    if align == "center":
        x = x - w // 2
    elif align == "right":
        x = x - w
    for pass_ in ((1, shadow), (0, color)) if shadow is not None else ((0, color),):
        off, col = pass_
        cx = x
        for ch in s:
            g = G[ch]
            for gy, row in enumerate(g):
                for gx, v in enumerate(row):
                    if v == "#":
                        cv.rect(cx + gx * scale + off * scale, y + gy * scale + off * scale, scale, scale, col)
            cx += (len(g[0]) + gap) * scale
    return w
